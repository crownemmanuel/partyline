//! livekit-server sidecar: write livekit.yaml, spawn, health-check :7880, restart on crash,
//! kill on exit (and kill a stale one left by a crashed previous run).
use serde::Serialize;
use std::path::{Path, PathBuf};
use std::process::Stdio;
use std::sync::{Arc, Mutex};
use std::time::Duration;
use tokio::process::{Child, Command};
use tokio::sync::watch;

#[derive(Clone, Debug, Serialize, Default)]
#[serde(rename_all = "camelCase")]
pub struct SidecarStatus {
    pub running: bool,
    pub restarts: u32,
    pub last_error: Option<String>,
}

#[derive(Clone)]
pub struct SidecarConfig {
    pub bin: PathBuf,
    pub data_dir: PathBuf,
    pub port: u16,
    pub tcp_port: u16,
    pub udp_start: u16,
    pub udp_end: u16,
    pub api_key: String,
    pub api_secret: String,
}

pub struct Sidecar {
    pub status: Arc<Mutex<SidecarStatus>>,
    node_ip: watch::Sender<String>,
    stop: watch::Sender<bool>,
    task: tokio::task::JoinHandle<()>,
}

/// Next to our executable (Tauri externalBin / `cargo run` copy), else PATH.
pub fn find_binary() -> PathBuf {
    let name = if cfg!(windows) { "livekit-server.exe" } else { "livekit-server" };
    if let Ok(p) = std::env::var("PARTYLINE_LIVEKIT_BIN") {
        return p.into();
    }
    if let Some(dir) = std::env::current_exe().ok().and_then(|e| e.parent().map(Path::to_path_buf)) {
        let p = dir.join(name);
        if p.exists() {
            return p;
        }
    }
    name.into()
}

fn write_yaml(c: &SidecarConfig, node_ip: &str) -> std::io::Result<PathBuf> {
    let yaml = format!(
        "# generated by PartyLine; rewritten on every start\nport: {port}\nbind_addresses: [\"127.0.0.1\"]\nrtc:\n  tcp_port: {tcp}\n  port_range_start: {us}\n  port_range_end: {ue}\n  use_external_ip: false\n  node_ip: {node_ip}\nkeys:\n  {key}: {secret}\nroom:\n  auto_create: true\n  empty_timeout: 86400\nlogging:\n  level: warn\n",
        port = c.port, tcp = c.tcp_port, us = c.udp_start, ue = c.udp_end, key = c.api_key, secret = c.api_secret
    );
    let p = c.data_dir.join("livekit.yaml");
    std::fs::write(&p, yaml)?;
    Ok(p)
}

fn kill_stale(pid_file: &Path) {
    let Ok(pid) = std::fs::read_to_string(pid_file) else { return };
    let pid = pid.trim();
    if pid.is_empty() {
        return;
    }
    #[cfg(unix)]
    {
        // only kill it if it really is a livekit-server
        let out = std::process::Command::new("ps").args(["-p", pid, "-o", "comm="]).output();
        if out.map(|o| String::from_utf8_lossy(&o.stdout).contains("livekit")).unwrap_or(false) {
            tracing::warn!("killing stale livekit-server pid {pid}");
            let _ = std::process::Command::new("kill").arg(pid).status();
            std::thread::sleep(Duration::from_millis(300));
        }
    }
    #[cfg(windows)]
    {
        let _ = std::process::Command::new("taskkill").args(["/PID", pid, "/F"]).status();
    }
    let _ = std::fs::remove_file(pid_file);
}

pub async fn healthy(port: u16) -> bool {
    let Ok(Ok(mut s)) = tokio::time::timeout(Duration::from_millis(500), tokio::net::TcpStream::connect(("127.0.0.1", port))).await else { return false };
    use tokio::io::{AsyncReadExt, AsyncWriteExt};
    if s.write_all(b"GET / HTTP/1.0\r\nHost: localhost\r\n\r\n").await.is_err() {
        return false;
    }
    let mut buf = [0u8; 64];
    matches!(tokio::time::timeout(Duration::from_millis(500), s.read(&mut buf)).await, Ok(Ok(n)) if n > 12 && buf.starts_with(b"HTTP/1.") && &buf[9..12] == b"200")
}

impl Sidecar {
    pub fn start(cfg: SidecarConfig, node_ip: String) -> Sidecar {
        let status = Arc::new(Mutex::new(SidecarStatus::default()));
        let (ip_tx, ip_rx) = watch::channel(node_ip);
        let (stop_tx, stop_rx) = watch::channel(false);
        let task = tokio::spawn(supervise(cfg, status.clone(), ip_rx, stop_rx));
        Sidecar { status, node_ip: ip_tx, stop: stop_tx, task }
    }
    /// LAN IP changed: rewrite config and restart.
    pub fn set_node_ip(&self, ip: String) {
        let _ = self.node_ip.send(ip);
    }
    pub async fn stop(self) {
        let _ = self.stop.send(true);
        let _ = tokio::time::timeout(Duration::from_secs(5), self.task).await;
    }
    pub async fn wait_healthy(&self, port: u16, timeout: Duration) -> bool {
        let t0 = std::time::Instant::now();
        while t0.elapsed() < timeout {
            if healthy(port).await {
                return true;
            }
            tokio::time::sleep(Duration::from_millis(100)).await;
        }
        false
    }
}

async fn supervise(cfg: SidecarConfig, status: Arc<Mutex<SidecarStatus>>, mut ip_rx: watch::Receiver<String>, mut stop_rx: watch::Receiver<bool>) {
    let pid_file = cfg.data_dir.join("livekit.pid");
    kill_stale(&pid_file);
    let mut backoff = 1u64;
    let mut first = true;
    loop {
        let ip = ip_rx.borrow_and_update().clone();
        let child = write_yaml(&cfg, &ip).and_then(|yaml| spawn(&cfg, &yaml));
        let mut child: Child = match child {
            Ok(c) => c,
            Err(e) => {
                let msg = format!("cannot start livekit-server ({}): {e}", cfg.bin.display());
                tracing::error!("{msg}");
                status.lock().unwrap().last_error = Some(msg);
                tokio::select! {
                    _ = tokio::time::sleep(Duration::from_secs(backoff)) => {}
                    _ = stop_rx.changed() => return,
                }
                backoff = (backoff * 2).min(10);
                continue;
            }
        };
        if let Some(pid) = child.id() {
            let _ = std::fs::write(&pid_file, pid.to_string());
        }
        if !first {
            status.lock().unwrap().restarts += 1;
        }
        first = false;
        // mark running once the port answers
        let st = status.clone();
        let port = cfg.port;
        let health = tokio::spawn(async move {
            for _ in 0..100 {
                if healthy(port).await {
                    let mut s = st.lock().unwrap();
                    s.running = true;
                    s.last_error = None;
                    return;
                }
                tokio::time::sleep(Duration::from_millis(100)).await;
            }
        });
        let started = std::time::Instant::now();
        let restart_for_ip;
        tokio::select! {
            r = child.wait() => {
                restart_for_ip = false;
                let msg = format!("livekit-server exited: {}", r.map(|s| s.to_string()).unwrap_or_else(|e| e.to_string()));
                tracing::warn!("{msg}");
                let mut s = status.lock().unwrap();
                s.running = false;
                s.last_error = Some(msg);
            }
            _ = ip_rx.changed() => {
                restart_for_ip = true;
                tracing::info!("LAN IP changed, restarting livekit-server");
            }
            _ = stop_rx.changed() => {
                health.abort();
                let _ = child.kill().await;
                let _ = std::fs::remove_file(&pid_file);
                status.lock().unwrap().running = false;
                return;
            }
        }
        health.abort();
        let _ = child.kill().await;
        status.lock().unwrap().running = false;
        if restart_for_ip {
            continue;
        }
        if started.elapsed() > Duration::from_secs(30) {
            backoff = 1;
        }
        tokio::select! {
            _ = tokio::time::sleep(Duration::from_secs(backoff)) => {}
            _ = stop_rx.changed() => return,
        }
        backoff = (backoff * 2).min(10);
    }
}

fn spawn(cfg: &SidecarConfig, yaml: &Path) -> std::io::Result<Child> {
    let log = std::fs::OpenOptions::new().create(true).append(true).open(cfg.data_dir.join("livekit.log"))?;
    let log2 = log.try_clone()?;
    let mut cmd = Command::new(&cfg.bin);
    cmd.arg("--config").arg(yaml).stdin(Stdio::null()).stdout(Stdio::from(log)).stderr(Stdio::from(log2)).kill_on_drop(true);
    #[cfg(windows)]
    {
        cmd.creation_flags(0x08000000); // CREATE_NO_WINDOW
    }
    cmd.spawn()
}
